import assert from 'node:assert/strict';
import './handling-check.mjs';
import {COMPOUNDS,normalizeTuning,drivingAssists,PersonalBestDelta,CarMastery} from '../public/js/RaceStrategy.js';
import {Track} from '../public/js/track.js';
import {RacePhysics} from '../public/js/physics.js';
assert.equal(normalizeTuning({pressure:999,finalDrive:-10}).pressure,36);
assert.equal(normalizeTuning({finalDrive:-10}).finalDrive,0.8);
assert.equal(drivingAssists('fm8',{steering:true,autoBrake:true,abs:false}).steering,false);
assert.equal(drivingAssists('horizon',{steering:true}).steering,true);
assert.ok(COMPOUNDS.Soft.grip>COMPOUNDS.Medium.grip&&COMPOUNDS.Soft.wear>COMPOUNDS.Hard.wear);
const track=new Track(777,'oval'),rp=new RacePhysics(track);rp.setGameMode('horizon');rp.rewindAllowed=true;rp.racing=true;
const c=rp.addCar({id:1,isLocal:true,startIndex:100,lateral:0,laps:99});c.raceLocked=false;rp.configureStrategy(c,{compound:'Soft',tuning:{finalDrive:1.1}});
c.input.throttle=1;
for(let i=0;i<720;i++)rp.fixedStep(1/60);
assert.equal(c.rewindHistory.count,201,'history is bounded to ten seconds at 20Hz');
const time=rp.time,wear=c.tireWear[0];c.compound='Wet';rp.setRewinding(true);
for(let i=0;i<120;i++)rp.fixedStep(1/60);
assert.ok(rp.time<time-1.9&&rp.time>time-2.2,'holding rewind restores the simulation timeline');
assert.ok(c.tireWear[0]<=wear,'wheel wear is restored with the chassis');assert.equal(c.compound,'Soft','compound is restored across a pit/tire change');
rp.setRewinding(false);const restored=rp.time;
for(let i=0;i<60;i++)rp.fixedStep(1/60);
assert.ok(rp.time>restored+0.99);assert.equal(c.penalty,0,'rewind reentry must never create penalties');
rp.rewindAllowed=false;assert.equal(rp.setRewinding(true),false,'network/competitive rewind cannot be enabled by a command');
console.log('PASS bounded rewind, branch truncation, wheel/timer restore, clean resume and mode guard');
const pit=new RacePhysics(track);pit.racing=true;const p=pit.addCar({id:1,isLocal:true,startIndex:25,lateral:0,laps:99});p.raceLocked=false;
const index=Math.floor(track.count*0.015)+4,point=track.pts[index],side=track.side[index],lat=track.halfWidthAt[index]-1;
p.body.position.set(point.x+side.x*lat,point.y+0.62,point.z+side.z*lat);p.body.velocity.set(0,0,0);p.trackIdx=index;p.lateral=lat;p.syncFromBody();p.fuel=0.1;p.tireWear.fill(0.8);p.nextCompound='Hard';p.pitRequested=true;
for(let i=0;i<200;i++)pit.fixedStep(1/60);
assert.equal(p.compound,'Hard');assert.ok(p.fuel>0.99);assert.ok(p.tireWear.every(x=>x<0.01));
console.log('PASS physical pit-zone validation, timed tire replacement and refuel');
const pb=new PersonalBestDelta();for(let i=0;i<=256;i++)pb.update(Math.min(i/256,0.999999),i/256*100,0);
assert.equal(pb.finish(100,false),true);assert.ok(Math.abs(pb.update(0.5,45,1)+5)<0.01);assert.equal(pb.finish(90,true),false);
const mastery=new CarMastery();assert.equal(mastery.award('sector:1',40),40);assert.equal(mastery.award('sector:1',40),0);assert.equal(new CarMastery(1e9).level,50);
console.log('PASS same-position personal-best delta, dirty-lap exclusion and non-farmable mastery XP');

c.driverIntent={throttle:0.8,brake:0,steer:0.2,handbrake:0};c.wheelspin=0.5;c.assists=drivingAssists('horizon',{tcs:true});
for(let i=0;i<20;i++)rp.applyAssists(c,1/60);
assert.ok(Math.abs(c.input.throttle-0.6)<1e-9,'assist output must not recursively damp raw intent between messages');
console.log('PASS assists remain stable when main-thread input delivery stalls');
